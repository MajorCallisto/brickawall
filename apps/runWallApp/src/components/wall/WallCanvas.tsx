type WallCanvasProps = {
  /** Element that receives pointer events, so HTML overlays do not block them. */
  eventSource: RefObject<HTMLElement>;
  /** Container outside the event source for in-scene HTML. */
  uiLayer: RefObject<HTMLElement>;
};

export function WallCanvas({ eventSource, uiLayer }: WallCanvasProps) {
  const [perfSucks, degrade] = useState(false);
  const shadows = useRef<ComponentRef<typeof AccumulativeShadows>>(null);
  return (
    <Canvas
      shadows
      dpr={[1, perfSucks ? 1.5 : 2]}
      eventSource={eventSource}
      eventPrefix="client"
      camera={{ position: [20, 0.9, 20], fov: 26 }}
    >
      {/* PerformanceMonitor degrades quality when the frame rate drops */}
      <PerformanceMonitor onDecline={() => degrade(true)} />
      <color attach="background" args={["#f0f0f0"]} />
      {/*
        The Suspense boundary must live inside the Canvas. Without it, fiber
        hands the suspension to the outer React tree, and under the Next.js
        App Router (which vendors a React canary) that handoff never resolves,
        leaving the scene blank. See docs/decisions.
      */}
      <Suspense fallback={null}>
        <group position={[0, -0.5, 0]} rotation={[0, -0.75, 0]}>
          {SHOW_EXAMPLE_MODEL && <Scene />}
          <AccumulativeShadows
            ref={shadows}
            frames={100}
            alphaTest={0.75}
            opacity={0.8}
            // Neutral shadow; the example tinted its shadows red.
            color="#3e3e3d"
            scale={20}
            position={[0, -0.005, 0]}
          >
            <RandomizedLight
              amount={8}
              radius={6}
              ambient={0.5}
              intensity={Math.PI}
              position={[-1.5, 2.5, -2.5]}
              bias={0.001}
            />
          </AccumulativeShadows>
        </group>
        <Env perfSucks={perfSucks} />
      </Suspense>
      {/* The ground sits at y = -0.5 in world space (see the group above) */}
      {/* Soft shadows are re-baked each time a brick lands */}
      <BrickPlacer groundY={-0.5} shadows={shadows} uiLayer={uiLayer} />
    </Canvas>
  );
}

